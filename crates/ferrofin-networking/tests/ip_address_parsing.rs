/// The IPv6 address `expected` names, scope left out.
fn ipv6(expected: &str) -> IpAddr {
    let address = expected.split('%').next().unwrap_or(expected);
    IpAddr::V6(address.parse::<Ipv6Addr>().expect(expected))
}

/// `ParseIPv4_ValidAddress_Success`.
#[test]
fn valid_ipv4_addresses_parse() {
    for &(input, expected) in VALID_IPV4 {
        assert_eq!(
            try_parse_ip_address(input),
            Some(expected.parse().expect(expected)),
            "{input}"
        );
    }
}

/// `ParseIPv4_InvalidAddress_Failure` and
/// `ParseIPv4_InvalidAddress_ThrowsFormatExceptionWithInnerException`.
#[test]
fn invalid_ipv4_addresses_do_not_parse() {
    for &input in INVALID_IPV4.iter().chain(INVALID_IPV4_STANDALONE) {
        assert_eq!(try_parse_ip_address(input), None, "{input:?}");
    }
}

/// `TryParseIPv6_ValidAddress_RoundtripMatchesExpected`, brackets added
/// around every input that has none.
#[test]
fn valid_ipv6_addresses_parse() {
    for &(input, expected) in VALID_IPV6 {
        assert_eq!(try_parse_ip_address(input), Some(ipv6(expected)), "{input}");
        if !input.starts_with('[') {
            assert_eq!(
                try_parse_ip_address(&format!("[{input}]")),
                Some(ipv6(expected)),
                "[{input}]"
            );
        }
    }
}

/// `ParseIPv6_InvalidAddress_ThrowsFormatException` and
/// `ParseIPv6_InvalidAddress_ThrowsFormatExceptionWithNoInnerExceptionInNetfx`.
#[test]
fn invalid_ipv6_addresses_do_not_parse() {
    for &input in INVALID_IPV6 {
        assert_eq!(try_parse_ip_address(input), None, "{input:?}");
    }
}

/// `InvalidIpv6Addresses`' "IPv6 addresses including invalid IPv4 addresses".
#[test]
fn ipv6_addresses_holding_an_invalid_ipv4_address_do_not_parse() {
    for &v4 in INVALID_IPV4 {
        for prefix in [
            "3fff:ffff:ffff:ffff:ffff:ffff:ffff:",
            "::",
            "::FF:",
            "::5EFE:",
            "1::5EFE:",
        ] {
            let input = format!("{prefix}{v4}");
            assert_eq!(try_parse_ip_address(&input), None, "{input:?}");
        }
    }
}
